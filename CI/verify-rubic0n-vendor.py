#!/usr/bin/env python3
"""Fail fast when the pinned Rubic0n LuaJIT sources were not committed to Git.

src/luajit.h is a GENERATED header and need not exist before building.
This check runs immediately after checkout on each platform.
"""
from __future__ import annotations

from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "extern" / "LuaJIT"
REQUIRED = (
    "COPYRIGHT",
    ".relver",
    ".arenamp-upstream.txt",
    "Makefile",
    "src/Makefile",
    "src/Makefile.dep",
    "src/msvcbuild.bat",
    "src/lua.h",
    "src/lua.hpp",
    "src/luajit_rolling.h",  # luajit.h is generated by the LuaJIT build
    "src/lj_vm.h",
    "src/lj_gc.c",
    "src/lj_alloc_page.c",
    "src/host/genversion.lua",
    "src/host/buildvm.c",
    "dynasm/dynasm.lua",
)


def error(message: str) -> None:
    print(f"::error::{message}", file=sys.stderr)


def main() -> int:
    missing = [str(VENDOR / p) for p in REQUIRED if not (VENDOR / p).is_file()]
    if missing:
        error("Rubic0n source tree is incomplete after checkout.")
        for path in missing:
            print("  Missing:", path, file=sys.stderr)
        print("  Restore the complete extern/LuaJIT directory from this repository, then", file=sys.stderr)
        print("  run: git add -A .gitignore extern/LuaJIT CI .github/workflows/release-builds.yml", file=sys.stderr)
        return 1

    git_dir = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "--is-inside-work-tree"],
        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, check=False,
    )
    if git_dir.returncode == 0 and git_dir.stdout.strip() == "true":
        # An ignored source file can exist locally but disappear in Actions checkout.
        tracked = subprocess.run(
            ["git", "-C", str(ROOT), "ls-files", "--", "extern/LuaJIT"],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False,
        )
        if tracked.returncode:
            error("Unable to inspect Git-tracked LuaJIT sources: " + tracked.stderr.strip())
            return 1
        names = set(tracked.stdout.splitlines())
        absent = ["extern/LuaJIT/" + p for p in REQUIRED if "extern/LuaJIT/" + p not in names]
        if absent:
            error("Required Rubic0n files exist locally but are NOT tracked by Git.")
            for name in absent:
                print("  Not tracked:", name, file=sys.stderr)
            print("  Check .gitignore, then run: git add -A .gitignore extern/LuaJIT", file=sys.stderr)
            return 1
        if len(names) < 170:
            error(f"Only {len(names)} LuaJIT paths are tracked; the full source archive is expected.")
            return 1
        print(f"Verified Rubic0n: {len(names)} LuaJIT paths committed in Git.")
    else:
        print("Verified Rubic0n source files on disk (no Git checkout available).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
