# ArenaMP: Rubic0n LuaJIT 2.1 from locally vendored source (Windows x64).
# Requires MSVC 2022. No LuaJIT GitHub fetch or binary release is used.
param([Parameter(Mandatory=$true)][string]$Destination)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$global:LASTEXITCODE = 0

$project = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$vendor = Join-Path $project 'extern/LuaJIT'
$source = $vendor
$upstream = 'rubic0n-2.1-agentzh'
$branch = 'provided-source'

# Build only the source committed with ArenaMP: no network fetch, no implicit fallback.
if (-not (Test-Path -LiteralPath (Join-Path $source 'src/msvcbuild.bat'))) {
    throw "Vendored Rubic0n LuaJIT source is missing: $source"
}
Write-Host 'Using vendored Rubic0n LuaJIT 2.1 (no remote source fetch)'

# src/luajit.h is GENERATED by host/genversion.lua during msvcbuild.bat.
# Do not require generated headers before compiling the source.
foreach ($file in @('src/Makefile', 'src/msvcbuild.bat', 'src/luajit_rolling.h',
                    'src/lua.h', 'src/lua.hpp', 'src/lj_vm.h',
                    'src/host/genversion.lua', 'src/lj_alloc_page.c',
                    'dynasm/dynasm.lua', '.relver', 'COPYRIGHT')) {
    if (!(Test-Path -LiteralPath (Join-Path $source $file))) {
        throw "Incomplete LuaJIT source: $file missing from $source"
    }
}
$sourceId = @('src/msvcbuild.bat', 'src/lj_gc.c', 'src/lj_alloc_page.c', 'src/lj_record.c', 'src/Makefile') |
    ForEach-Object { (Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $source $_)).Hash.ToLowerInvariant() } |
    Join-String -Separator ':'
$sourceId = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($sourceId))).ToLowerInvariant()
# Include the source revision information when provided by CI/vendor_luajit.ps1.
$manifest = Join-Path $source '.arenamp-upstream.txt'
if (Test-Path -LiteralPath $manifest) {
    $revisionLine = @(Get-Content -LiteralPath $manifest | Where-Object { $_ -like 'commit=*' } | Select-Object -First 1)
    if ($revisionLine.Count -gt 0) { Write-Host "LuaJIT upstream $($revisionLine[0])" }
}

$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
if (!(Test-Path -LiteralPath $vswhere)) { throw 'vswhere.exe missing' }
$vsroot = @(& $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath) |
    Where-Object { $_ -and $_.Trim() } | Select-Object -First 1
if ($global:LASTEXITCODE -ne 0 -or !$vsroot) { throw 'MSVC C++ toolchain not found' }
$vcvars = Join-Path $vsroot 'VC/Auxiliary/Build/vcvars64.bat'
if (!(Test-Path -LiteralPath $vcvars)) { throw 'vcvars64.bat missing' }

# Never compile inside tracked extern/LuaJIT. The MSVC script generates hundreds
# of files: copy sources to a disposable build tree to keep the repository clean.
$buildRoot = Join-Path $project 'deps/_sources/luajit-msvc-work'
if (Test-Path -LiteralPath $buildRoot) { Remove-Item -LiteralPath $buildRoot -Recurse -Force }
New-Item -ItemType Directory -Force -Path $buildRoot | Out-Null
foreach ($name in @('src', 'dynasm')) {
    Copy-Item -LiteralPath (Join-Path $source $name) -Destination $buildRoot -Recurse -Force
}
Copy-Item -LiteralPath (Join-Path $source '.relver') -Destination $buildRoot -Force
$srcdir = Join-Path $buildRoot 'src'
$tempRoot = if ($env:RUNNER_TEMP) { $env:RUNNER_TEMP } else { $env:TEMP }
$batchFile = Join-Path $tempRoot 'arenamp-build-luajit-official.cmd'
@(
    '@echo off',
    # vcvars64.bat does not accept VsDevCmd.bat's -no_logo option.
    "call `"$vcvars`"",
    'if errorlevel 1 exit /b 1',
    'where cl.exe >nul 2>nul',
    'if errorlevel 1 (echo ERROR: MSVC compiler is not available after vcvars64.bat & exit /b 1)',
    "cd /d `"$srcdir`"",
    'if errorlevel 1 exit /b 1',
    'call msvcbuild.bat',
    'exit /b %errorlevel%'
) | Set-Content -LiteralPath $batchFile -Encoding Ascii
Write-Host 'Compiling vendored Rubic0n LuaJIT 2.1 with MSVC 2022 x64...'
& cmd.exe /d /c $batchFile
if ($global:LASTEXITCODE -ne 0) { throw "LuaJIT MSVC compilation failed ($global:LASTEXITCODE)" }

$includes = @('lua.h', 'lua.hpp', 'luaconf.h', 'lualib.h', 'lauxlib.h', 'luajit.h')
foreach ($name in ($includes + @('lua51.lib', 'lua51.dll'))) {
    if (!(Test-Path -LiteralPath (Join-Path $srcdir $name))) { throw "LuaJIT build missing output: $name" }
}
$includeDir = Join-Path $Destination 'include'
$libDir = Join-Path $Destination 'lib'
$binDir = Join-Path $Destination 'bin'
foreach ($path in @($includeDir, $libDir, $binDir)) { New-Item -ItemType Directory -Force -Path $path | Out-Null }
foreach ($name in $includes) { Copy-Item -LiteralPath (Join-Path $srcdir $name) -Destination $includeDir -Force }
Copy-Item -LiteralPath (Join-Path $srcdir 'lua51.lib') -Destination $libDir -Force
Copy-Item -LiteralPath (Join-Path $srcdir 'lua51.dll') -Destination $binDir -Force
if (Test-Path -LiteralPath (Join-Path $srcdir 'jit')) {
    Copy-Item -LiteralPath (Join-Path $srcdir 'jit') -Destination $binDir -Recurse -Force
}
# Written only after verifying outputs to avoid false cache hits.
@("upstream=$upstream", "branch=$branch", "source-script-sha256=$sourceId", 'toolchain=MSVC-x64') |
  Set-Content -LiteralPath (Join-Path $Destination '.arenamp-source-build') -Encoding Ascii
Write-Host 'Rubic0n LuaJIT 2.1 source build completed.'
